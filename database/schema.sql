-- My Engineering Degree OS: Supabase schema
-- Run this entire script in Supabase Dashboard > SQL Editor.
-- Uses a JSONB row payload to preserve your current CSV-like frontend structure.

create table if not exists public.degree_records (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    dataset text not null check (
        dataset in (
            'semesters',
            'courses',
            'university_syllabus',
            'calendar',
            'assessments',
            'scores',
            'plan_checklist'
        )
    ),
    position integer not null default 0,
    row_data jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists degree_records_user_dataset_position_idx
    on public.degree_records (user_id, dataset, position);

alter table public.degree_records enable row level security;

drop policy if exists "Users can read their own degree records" on public.degree_records;
create policy "Users can read their own degree records"
    on public.degree_records for select
    to authenticated
    using (auth.uid() = user_id);

drop policy if exists "Users can insert their own degree records" on public.degree_records;
create policy "Users can insert their own degree records"
    on public.degree_records for insert
    to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "Users can update their own degree records" on public.degree_records;
create policy "Users can update their own degree records"
    on public.degree_records for update
    to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own degree records" on public.degree_records;
create policy "Users can delete their own degree records"
    on public.degree_records for delete
    to authenticated
    using (auth.uid() = user_id);

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.degree_records to authenticated;
grant usage, select on sequence public.degree_records_id_seq to authenticated;
